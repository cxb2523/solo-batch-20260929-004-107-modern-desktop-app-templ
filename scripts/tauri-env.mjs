#!/usr/bin/env node
/**
 * Tauri 环境配置与能力（capabilities）生成器。
 *
 * 配置组织决策：
 *   采用“单份主文件 src-tauri/tauri.conf.json（基线，定义完整窗口/打包/插件）
 *   + 每环境一份薄覆写 tauri.<env>.conf.json（只写差异）”，不拆三份完整配置，
 *   避免窗口定义与能力集合在副本之间漂移。本脚本把两者深度合并（windows 数组
 *   按 label 逐字段合并），再叠加平台覆写 tauri.windows.conf.json，产出供
 *   `tauri build --config` 使用的最终配置 src-tauri/tauri.conf.<env>.json。
 *
 *   capabilities 同理：单一真源在本文件的白名单常量里，按环境重写
 *   capabilities/desktop.json 与 capabilities/migrated.json。
 *
 * 前端（构建期静态注入，可摇树）与 Rust（运行时读配置）的分工及“冲突时以构建期
 * 为准”的约定见 vite.config.ts / src/config/runtime.ts / src-tauri/src/lib.rs。
 *
 * 用法：
 *   node scripts/tauri-env.mjs dev|staging|prod
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ENVS = ['dev', 'staging', 'prod'];

const here = dirname(fileURLToPath(import.meta.url));
export const TAURI_DIR = resolve(here, '..', 'src-tauri');

export const ENV_SPEC = {
	dev: {
		identifier: 'com.example.app.dev',
		endpoint: 'http://localhost:1421/updates/{{target}}/{{arch}}/{{current_version}}',
		devtools: true,
	},
	staging: {
		identifier: 'com.example.app.staging',
		endpoint: 'https://updates.staging.example.com/{{target}}/{{arch}}/{{current_version}}',
		devtools: true,
	},
	prod: {
		identifier: 'com.example.app',
		endpoint: 'https://updates.example.com/{{target}}/{{arch}}/{{current_version}}',
		devtools: false,
	},
};

/**
 * 每个环境的能力白名单（单一真源）。
 * 只允许出现在这里的标识符；verify 阶段会逐字节比对，出现白名单外的命令即判越权。
 */
const fsScopeAppDocsDownloads = {
	identifier: 'fs:scope',
	allow: ['$APP/*', '$DOCUMENT/*', '$DOWNLOAD/*'],
};

const WINDOW_COMMANDS = [
	'core:window:allow-maximize',
	'core:window:allow-unmaximize',
	'core:window:allow-minimize',
	'core:window:allow-unminimize',
	'core:window:allow-close',
	'core:window:allow-set-decorations',
	'core:window:allow-set-size',
	'core:window:allow-set-fullscreen',
	'core:window:allow-set-focus',
	'core:window:allow-start-dragging',
	'core:window:allow-toggle-maximize',
];

const COMMON_COMMANDS = [
	'core:default',
	...WINDOW_COMMANDS,
	'updater:default',
	'store:default',
	'autostart:default',
	'opener:default',
	'log:default',
	'shell:allow-open',
	'shell:default',
	'dialog:allow-message',
	'dialog:default',
	'notification:default',
	'os:allow-platform',
	'os:allow-version',
	'os:allow-os-type',
	'os:allow-family',
	'os:allow-arch',
	'os:allow-exe-extension',
	'os:allow-locale',
	'os:allow-hostname',
	'os:default',
	'process:allow-restart',
	'process:default',
	// 前端在应用文档/下载目录内的最小文件操作命令（不含任何通配 scope）。
	'fs:allow-write-file',
	'fs:allow-read-dir',
	'fs:allow-mkdir',
	fsScopeAppDocsDownloads,
];

/** dev / staging 额外放行的命令：devtools 与 fs 递归写入（含通配语义的 scope）。 */
const NON_PROD_ONLY_COMMANDS = [
	'core:webview:allow-internal-toggle-devtools',
	'fs:default',
	'fs:allow-download-write-recursive',
];

export function capabilityPermissions(env) {
	if (env === 'prod') return [...COMMON_COMMANDS];
	return [...COMMON_COMMANDS, ...NON_PROD_ONLY_COMMANDS];
}

export function buildCapabilities(env) {
	const perms = capabilityPermissions(env);
	const note = `AUTO-GENERATED by scripts/tauri-env.mjs for env=${env}. DO NOT EDIT BY HAND — `
		+ 'prod 必须不含 core:webview:allow-internal-toggle-devtools 与 fs 通配符（fs:default/'
		+ 'fs:allow-download-write-recursive / 宽泛 fs:scope）；verify:env 会强制核对。';
	const desktop = {
		description: note,
		identifier: 'desktop-capability',
		platforms: ['macOS', 'windows', 'linux'],
		windows: ['main'],
		permissions: env === 'prod'
			? ['updater:default', 'store:default', 'autostart:default', 'opener:default', 'log:default',
				'core:window:allow-toggle-maximize']
			: ['updater:default', 'store:default', 'autostart:default', 'opener:default', 'log:default',
				'core:window:allow-toggle-maximize',
				'core:webview:allow-internal-toggle-devtools',
				'fs:allow-download-write-recursive'],
	};
	const migrated = {
		description: note,
		identifier: 'migrated',
		description: 'permissions that were migrated from v1',
		local: true,
		windows: ['main'],
		permissions: perms,
	};
	return { desktop, migrated };
}

function isPlainObject(value) {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** 深度合并：对象逐键合并；其余类型（含数组）整体用覆写层替换。 */
function deepMerge(base, override) {
	if (!isPlainObject(base) || !isPlainObject(override)) return override;
	const out = { ...base };
	for (const [key, value] of Object.entries(override)) {
		if (isPlainObject(value) && isPlainObject(base[key])) {
			out[key] = deepMerge(base[key], value);
		} else {
			out[key] = value;
		}
	}
	return out;
}

/**
 * windows 数组按 label 合并（对齐 tauri CLI 的平台覆写语义）：
 * 覆写层里 label 相同的窗口只覆盖出现的字段，保证窗口能力可薄覆写而不丢主文件定义。
 */
function mergeWindows(baseWindows, overrideWindows) {
	if (!Array.isArray(baseWindows) || !Array.isArray(overrideWindows)) return overrideWindows ?? baseWindows;
	return baseWindows.map((win) => {
	// 平台/环境覆写文件里只保留了 main 这一个 label，其它标签直接沿用基线。
	const patch = overrideWindows.find(w => w.label === win.label);
		return patch ? deepMerge(win, patch) : win;
	});
}

function readJson(rel) {
	return JSON.parse(readFileSync(resolve(TAURI_DIR, rel), 'utf-8'));
}

/** 递归删除 JSON 里所有 $ 前缀的说明性键（$comment/$schema），Tauri schema 不允许额外属性。 */
function stripDollarKeys(value) {
	if (Array.isArray(value)) return value.map(stripDollarKeys);
	if (isPlainObject(value)) {
		return Object.fromEntries(
			Object.entries(value)
				.filter(([key]) => !key.startsWith('$'))
				.map(([key, val]) => [key, stripDollarKeys(val)]),
		);
	}
	return value;
}

function writeJson(rel, value) {
	const target = resolve(TAURI_DIR, rel);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, JSON.stringify(value, null, 2) + '\n', 'utf-8');
}

/**
 * 生成并落盘某环境的最终 tauri 配置与 capabilities。
 * @param {string} env dev|staging|prod
 * @param {{ platform?: boolean }} options
 */
export function generateEnv(env, { platform = true } = {}) {
	if (!ENVS.includes(env)) throw new Error(`unknown env ${env}; expected one of ${ENVS.join('|')}`);
	const spec = ENV_SPEC[env];

	let config = stripDollarKeys(readJson('tauri.conf.json'));
	// 合并顺序对齐 tauri CLI：基线 <- 平台覆写 <- 环境覆写（环境优先级最高）。
	if (platform && process.platform === 'win32') {
		config = deepMerge(config, stripDollarKeys(readJson('tauri.windows.conf.json')));
	}
	config = deepMerge(config, stripDollarKeys(readJson(`tauri.${env}.conf.json`)));

	// windows 数组回退为按 label 合并的结果。
	const envOverride = stripDollarKeys(readJson(`tauri.${env}.conf.json`));
	const base = stripDollarKeys(readJson('tauri.conf.json'));
	let windows = base.app.windows;
	if (platform && process.platform === 'win32') {
		windows = mergeWindows(windows, stripDollarKeys(readJson('tauri.windows.conf.json')).app?.windows ?? []);
	}
	windows = mergeWindows(windows, envOverride.app?.windows ?? []);
	config.app.windows = windows;

	// 强制断言覆写文件声明的关键值与 ENV_SPEC 一致，防止源文件被手改后漂移。
	if (config.identifier !== spec.identifier) {
		throw new Error(`[tauri-env] ${env}: identifier drift: want ${spec.identifier}, got ${config.identifier}`);
	}
	if (!Array.isArray(config.plugins?.updater?.endpoints) || config.plugins.updater.endpoints[0] !== spec.endpoint) {
		throw new Error(`[tauri-env] ${env}: updater endpoint drift: want ${spec.endpoint}`);
	}
	if (config.app.windows[0].devtools !== spec.devtools) {
		throw new Error(`[tauri-env] ${env}: window devtools drift: want ${spec.devtools}`);
	}

	// 更新签名公钥/产物开关来自 CI 共享环境变量；本地无签名时 prod 仍可出未签名安装包。
	const pubkey = process.env.TAURI_UPDATER_PUBKEY ?? '';
	config.plugins.updater.pubkey = pubkey;
	const signed = process.env.TAURI_SIGNING_PRIVATE_KEY !== undefined && process.env.TAURI_SIGNING_PRIVATE_KEY !== '';
	if (env === 'dev') {
		config.bundle.createUpdaterArtifacts = false;
	} else if (signed) {
		config.bundle.createUpdaterArtifacts = true;
	}

	// 让 tauri 驱动的 vite 进程使用与当前环境一致的 mode（默认 build=production/
	// dev=development 并不在我们的三态里），否则 runtimeConfig 会因缺 VITE_APP_ENV 而报错。
	config.build.beforeDevCommand = `pnpm start:${env}`;
	config.build.beforeBuildCommand = `pnpm build:frontend:${env}`;

	writeJson(`tauri.conf.${env}.json`, config);

	const caps = buildCapabilities(env);
	writeJson('capabilities/desktop.json', caps.desktop);
	writeJson('capabilities/migrated.json', caps.migrated);
	return config;
}

if (process.argv[1] && resolve(normalize(process.argv[1])) === fileURLToPath(import.meta.url)) {
	const env = process.argv[2];
	if (!ENVS.includes(env)) {
		console.error(`usage: node scripts/tauri-env.mjs <${ENVS.join('|')}>`);
		process.exit(2);
	}
	generateEnv(env);
	console.log(`[tauri-env] generated tauri.conf.${env}.json + capabilities for ${env}`);
}
